#!/usr/bin/env node
/**
 * RIL100 Betriebsstellen → SQL migration (billing spec section 9).
 *
 * Reads the DB "Betriebsstellencodes Internetliste" (.xlsx, first sheet =
 * newest Stand) and writes a migration that
 *   1. fills the reference table public.ril100_betriebsstellen, and
 *   2. adds every code to operational_locations of every organisation that
 *      does not have that code yet (existing Betriebsstellen stay untouched).
 *
 * Usage:
 *   node scripts/ril100-import.mjs <list.xlsx> <stand YYYY-MM-DD> <out.sql>
 *   node scripts/ril100-import.mjs <list.xlsx> <stand YYYY-MM-DD> <out-dir> --parts
 *     → small files for the Supabase SQL editor (run 01, 02, … in order;
 *       every part can be run again safely).
 *
 * Rules
 *   - Code: as published (trimmed); inner spaces are significant ("AA  G"
 *     and "AAG" are different points).
 *   - Name: RIL100-Langname with whitespace runs collapsed.
 *   - A code listed twice (e.g. "Planung" now, "Betrieb" from 2029) keeps
 *     the row valid on the Stand date (latest Datum-Ab ≤ Stand, else the
 *     earliest).
 *   - Active: Betriebszustand "Betrieb" or empty. "stillg.", "a.B.",
 *     "Planung", "Studie" are imported as inactive (searchable in
 *     Einstellungen, not offered in the shift forms).
 */
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const ExcelJS = require('exceljs')

const [, , input, stand, out, flag] = process.argv
const PARTS = flag === '--parts'
if (!input || !/^\d{4}-\d{2}-\d{2}$/.test(stand ?? '') || !out) {
  console.error('Usage: node scripts/ril100-import.mjs <list.xlsx> <stand YYYY-MM-DD> <out.sql>')
  process.exit(1)
}
const standNum = Number(stand.replace(/-/g, ''))
const standLabel = `${stand.slice(8, 10)}.${stand.slice(5, 7)}.${stand.slice(0, 4)}`

const wb = new ExcelJS.Workbook()
await wb.xlsx.readFile(input)
const ws = wb.worksheets[0]

// Header row: find the row that starts with PLC / RL100-Code.
let headerRow = 0
const col = {}
ws.eachRow((row, i) => {
  if (headerRow) return
  const v = row.values.map((x) => String(x ?? '').trim())
  if (v.includes('RL100-Code')) {
    headerRow = i
    v.forEach((name, idx) => { if (name) col[name] = idx })
  }
})
for (const need of ['RL100-Code', 'RL100-Langname', 'Typ-Kurz', 'Betriebszustand']) {
  if (!col[need]) throw new Error(`Spalte "${need}" nicht gefunden`)
}
const plcCol = col['PLC-Gesamt'] ?? col['PLC']
const abCol = col['Datum-Ab']

const cell = (row, idx) => {
  if (!idx) return ''
  const v = row.values[idx]
  if (v == null) return ''
  if (typeof v === 'object' && 'result' in v) return String(v.result ?? '')
  if (typeof v === 'object' && 'richText' in v) return v.richText.map((t) => t.text).join('')
  return String(v)
}

const byCode = new Map()
let read = 0
ws.eachRow((row, i) => {
  if (i <= headerRow) return
  const code = cell(row, col['RL100-Code']).trim()
  const name = cell(row, col['RL100-Langname']).replace(/\s+/g, ' ').trim()
  if (!code || !name) return
  read++
  const rec = {
    code,
    name,
    shortName: cell(row, col['RL100-Kurzname']).replace(/\s+/g, ' ').trim(),
    typ: cell(row, col['Typ-Kurz']).trim(),
    status: cell(row, col['Betriebszustand']).trim(),
    plc: cell(row, plcCol).trim(),
    ab: Number(cell(row, abCol)) || 0,
  }
  const key = code.toUpperCase()
  const list = byCode.get(key) ?? []
  list.push(rec)
  byCode.set(key, list)
})

function pick(list) {
  if (list.length === 1) return list[0]
  const valid = list.filter((r) => r.ab && r.ab <= standNum).sort((a, b) => b.ab - a.ab)
  if (valid.length) return valid[0]
  return [...list].sort((a, b) => a.ab - b.ab)[0]
}

const ACTIVE = new Set(['Betrieb', ''])

function mapType(typ, name) {
  const t = `${typ} ${name}`.toLowerCase()
  if (/\b(bw|betriebswerk|werkstatt|instandhaltung)\b/.test(t)) return 'workshop'
  if (/\b(gbf|rbf|abstellanlage|abst)\b/.test(t)) return 'yard'
  if (/^(anst|awanst|ne-anst|ne-awanst|abzw-anst)$/i.test(typ)) return 'yard'
  if (/^(bf|hp|bft|ne-bf|ne-hp|ne-bft|vp-bf|vp-hp|hst|ne-hst)$/i.test(typ)) return 'station'
  return 'other'
}

const rows = [...byCode.values()].map(pick).sort((a, b) => a.code.localeCompare(b.code))
const q = (s) => (s === '' || s == null ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`)

const lines = []
lines.push(`-- ===========================================================================
-- RIL100 Betriebsstellen (DB-Internetliste, Stand ${standLabel}) — billing spec
-- section 9. Generated by scripts/ril100-import.mjs; do not edit by hand.
--
-- ${read} rows read, ${rows.length} unique codes.
-- Requires 20261125120000_billing_rules.sql (columns ril100_type, …).
-- Adds every code to operational_locations of every organisation that does
-- not have it yet. Existing Betriebsstellen (same code) stay untouched.
-- ===========================================================================

CREATE TABLE IF NOT EXISTS public.ril100_betriebsstellen (
  code        TEXT PRIMARY KEY,
  name        TEXT NOT NULL,
  short_name  TEXT,
  typ         TEXT,
  status      TEXT,
  plc         TEXT,
  valid_from  DATE,
  stand       DATE NOT NULL
);
COMMENT ON TABLE public.ril100_betriebsstellen IS
  'Reference copy of the DB RIL100 list (one row per code, state on the Stand date). Source for operational_locations imports.';
ALTER TABLE public.ril100_betriebsstellen ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ril100_betriebsstellen FROM anon, authenticated;

DROP TABLE IF EXISTS pg_temp._ril100;
CREATE TEMP TABLE _ril100 (LIKE public.ril100_betriebsstellen);
`)

const CHUNK = 1000
for (let i = 0; i < rows.length; i += CHUNK) {
  const part = rows.slice(i, i + CHUNK)
  lines.push('INSERT INTO _ril100 (code, name, short_name, typ, status, plc, valid_from, stand) VALUES')
  lines.push(
    part
      .map((r) => {
        const ab = r.ab ? `'${String(r.ab).slice(0, 4)}-${String(r.ab).slice(4, 6)}-${String(r.ab).slice(6, 8)}'` : 'NULL'
        return `(${q(r.code)}, ${q(r.name)}, ${q(r.shortName)}, ${q(r.typ)}, ${q(r.status)}, ${q(r.plc)}, ${ab}, '${stand}')`
      })
      .join(',\n') + ';',
  )
}

const typeCase = (alias) => `CASE
      WHEN ${alias}.name ~* '\\m(bw|betriebswerk|werkstatt|instandhaltung)\\M' OR ${alias}.typ ~* '^bw$' THEN 'workshop'
      WHEN ${alias}.name ~* '\\m(gbf|rbf|abstellanlage|abst)\\M' THEN 'yard'
      WHEN ${alias}.typ ~* '^(anst|awanst|ne-anst|ne-awanst)$' THEN 'yard'
      WHEN ${alias}.typ ~* '^(bf|hp|bft|ne-bf|ne-hp|ne-bft|vp-bf|vp-hp|hst|ne-hst)$' THEN 'station'
      ELSE 'other'
    END`

// Codes are the identity of a Betriebsstelle (spec section 9); the RIL100
// list has 17 names shared by two codes (e.g. Frankfurt (Oder) Pbf = BFP and
// BFP P). Name uniqueness therefore applies to the organisation's own entries
// only — same as migration 20261125125000.
const NAME_RULE = `-- Unique names only for the organisation's own entries; imported RIL100
-- rows are unique by code (uq_operational_locations_org_code).
ALTER TABLE public.operational_locations
  DROP CONSTRAINT IF EXISTS operational_locations_organization_id_name_key;
CREATE UNIQUE INDEX IF NOT EXISTS uq_operational_locations_org_name_own
  ON public.operational_locations (organization_id, name)
  WHERE source IS NULL;
-- Codes: unique among own entries and among imported entries (an own code
-- may name a different place than RIL100, e.g. RMR) — as 20261126120000.
CREATE UNIQUE INDEX IF NOT EXISTS uq_operational_locations_org_code_own
  ON public.operational_locations (organization_id, upper(btrim(short_code)))
  WHERE source IS NULL AND short_code IS NOT NULL AND btrim(short_code) <> '';
CREATE UNIQUE INDEX IF NOT EXISTS uq_operational_locations_org_code_ril
  ON public.operational_locations (organization_id, upper(btrim(short_code)))
  WHERE source IS NOT NULL AND short_code IS NOT NULL AND btrim(short_code) <> '';
DROP INDEX IF EXISTS public.uq_operational_locations_org_code;
`

lines.push(`
${NAME_RULE}
-- Reference table: replace with this Stand.
DELETE FROM public.ril100_betriebsstellen;
INSERT INTO public.ril100_betriebsstellen SELECT * FROM _ril100;

-- Imported rows keep name/type/status in sync with this Stand (only rows
-- that came from an earlier RIL100 import; app-created ones are never
-- changed).
UPDATE public.operational_locations l
   SET name          = r.name,
       ril100_type   = r.typ,
       ril100_status = NULLIF(r.status, ''),
       plc_code      = r.plc,
       source        = 'RIL100 ${standLabel}',
       updated_at    = now()
  FROM _ril100 r
 WHERE l.source LIKE 'RIL100 %'
   AND upper(btrim(l.short_code)) = upper(r.code)
   AND (l.name, l.ril100_type, l.ril100_status, l.plc_code)
       IS DISTINCT FROM (r.name, r.typ, NULLIF(r.status, ''), r.plc);

-- New codes for every organisation, all searchable (closed/planned points
-- show their RIL100 status; admins can still archive single entries, which
-- later imports keep). Matching is on the exact code (case-insensitive,
-- trimmed). An own entry with the same code is skipped only when it is the
-- same place (same name, e.g. KAW Aachen West); otherwise both exist
-- (RMR: own "Rhein Maas Rail" and RIL100 "Mannheim Rbf").
INSERT INTO public.operational_locations
  (organization_id, name, short_code, type, is_active, ril100_type, ril100_status, plc_code, source)
SELECT o.id, r.name, r.code,
       ${typeCase('r')},
       TRUE,
       r.typ, NULLIF(r.status, ''), r.plc, 'RIL100 ${standLabel}'
  FROM public.organizations o
 CROSS JOIN _ril100 r
 WHERE NOT EXISTS (
         SELECT 1 FROM public.operational_locations l
          WHERE l.organization_id = o.id AND l.source IS NOT NULL
            AND upper(btrim(l.short_code)) = upper(r.code)
       )
   AND NOT EXISTS (
         SELECT 1 FROM public.operational_locations l
          WHERE l.organization_id = o.id AND l.source IS NULL
            AND upper(btrim(l.short_code)) = upper(r.code)
            AND public.location_search_norm(l.name) = public.location_search_norm(r.name)
       );

DROP TABLE IF EXISTS pg_temp._ril100;
ANALYZE public.operational_locations;
`)

if (PARTS) {
  const { mkdirSync } = await import('node:fs')
  mkdirSync(out, { recursive: true })
  const ROWS = 2500
  const total = Math.ceil(rows.length / ROWS) + 2
  const pad = (n) => String(n).padStart(2, '0')
  const head = (n, what) => `-- RIL100 Betriebsstellen (Stand ${standLabel}) — Teil ${n} von ${total}: ${what}\n-- Generated by scripts/ril100-import.mjs. Run the parts in order; each can be run again.\n\n`
  writeFileSync(`${out}/${pad(1)}_tabelle.sql`, head(1, 'Referenztabelle') + `CREATE TABLE IF NOT EXISTS public.ril100_betriebsstellen (
  code        TEXT PRIMARY KEY,
  name        TEXT NOT NULL,
  short_name  TEXT,
  typ         TEXT,
  status      TEXT,
  plc         TEXT,
  valid_from  DATE,
  stand       DATE NOT NULL
);
ALTER TABLE public.ril100_betriebsstellen ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ril100_betriebsstellen FROM anon, authenticated;
-- Older Stand rows are replaced by the parts that follow.
DELETE FROM public.ril100_betriebsstellen WHERE stand <> '${stand}';
`)
  for (let i = 0; i < rows.length; i += ROWS) {
    const n = i / ROWS + 2
    const part = rows.slice(i, i + ROWS)
    const values = part.map((r) => {
      const ab = r.ab ? `'${String(r.ab).slice(0, 4)}-${String(r.ab).slice(4, 6)}-${String(r.ab).slice(6, 8)}'` : 'NULL'
      return `(${q(r.code)}, ${q(r.name)}, ${q(r.shortName)}, ${q(r.typ)}, ${q(r.status)}, ${q(r.plc)}, ${ab}, '${stand}')`
    })
    writeFileSync(
      `${out}/${pad(n)}_daten_${part[0].code.replace(/[^A-Za-z0-9]/g, '')}-${part[part.length - 1].code.replace(/[^A-Za-z0-9]/g, '')}.sql`,
      head(n, `Kürzel ${part[0].code} bis ${part[part.length - 1].code} (${part.length})`) +
        'INSERT INTO public.ril100_betriebsstellen (code, name, short_name, typ, status, plc, valid_from, stand) VALUES\n' +
        values.join(',\n') +
        '\nON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name, short_name = EXCLUDED.short_name, typ = EXCLUDED.typ, status = EXCLUDED.status, plc = EXCLUDED.plc, valid_from = EXCLUDED.valid_from, stand = EXCLUDED.stand;\n',
    )
  }
  const final = lines[lines.length - 1]
    .replace(/DELETE FROM public\.ril100_betriebsstellen;\nINSERT INTO public\.ril100_betriebsstellen SELECT \* FROM _ril100;\n/, '')
    .replace(/FROM _ril100 r/g, 'FROM public.ril100_betriebsstellen r')
    .replace(/CROSS JOIN _ril100 r/g, 'CROSS JOIN public.ril100_betriebsstellen r')
    .replace(/DROP TABLE IF EXISTS pg_temp\._ril100;\n/g, '')
  writeFileSync(
    `${out}/${pad(total)}_betriebsstellen_uebernehmen.sql`,
    head(total, 'in die Betriebsstellen aller Organisationen übernehmen') +
      `DO $$ BEGIN\n  IF (SELECT count(*) FROM public.ril100_betriebsstellen WHERE stand = '${stand}') <> ${rows.length} THEN\n    RAISE EXCEPTION 'Es fehlen Daten-Teile: % von ${rows.length} Kürzeln geladen. Bitte alle Teile davor ausführen.', (SELECT count(*) FROM public.ril100_betriebsstellen WHERE stand = '${stand}');\n  END IF;\nEND $$;\n` +
      final,
  )
  console.log(`${total} Teile → ${out}`)
  process.exit(0)
}

writeFileSync(out, lines.join('\n'))
console.log(`${read} Zeilen gelesen, ${rows.length} eindeutige Kürzel, aktiv: ${rows.filter((r) => ACTIVE.has(r.status)).length}, inaktiv: ${rows.filter((r) => !ACTIVE.has(r.status)).length}`)
console.log(`→ ${out}`)
